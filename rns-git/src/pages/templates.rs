//! Page templates: the defaults and those an operator puts in place.

use super::*;

pub(super) fn render_template(config: &ServerConfig, template: &str, content: &str) -> String {
    let page = apply_template(&page_template(config, template), content, config);
    apply_template(&base_template(config), &page, config)
}

pub(super) fn error_page(node_name: &str, message: &str) -> Vec<u8> {
    default_base_template()
        .replace("{PAGE_CONTENT}", &format!(">Error\n\n{message}\n"))
        .replace("{NODE_NAME}", &m_escape(node_name))
        .replace("{VERSION}", env!("CARGO_PKG_VERSION"))
        .replace("{NAVIGATION}", "")
        .replace("{GEN_TIME}", "0ms")
        .into_bytes()
}

pub(super) fn error_response_bytes(err: &Error) -> Vec<u8> {
    protocol::status_bytes(protocol::RES_INVALID_REQ, err.to_string())
}

pub(super) fn base_template(config: &ServerConfig) -> String {
    load_template(config, "base").unwrap_or_else(|| default_base_template().to_string())
}

pub(super) fn page_template(config: &ServerConfig, template: &str) -> String {
    load_template(config, template).unwrap_or_else(|| default_page_template(template).to_string())
}

pub(super) fn default_page_template(template: &str) -> &'static str {
    match template {
        "no_ident" => {
            ">>No Identity\n\nThis page requires identification, and none was received.\n"
        }
        _ => "{PAGE_CONTENT}",
    }
}

pub(super) fn load_template(config: &ServerConfig, template: &str) -> Option<String> {
    if !template
        .chars()
        .all(|ch| ch.is_ascii_alphanumeric() || ch == '_' || ch == '-')
    {
        return None;
    }
    let path = config.templates_dir.join(format!("{template}.mu"));
    fs::read_to_string(path)
        .ok()
        .map(|template| template.trim_end().to_string())
}

pub(super) fn apply_template(template: &str, content: &str, config: &ServerConfig) -> String {
    template
        .replace("{NODE_NAME}", &m_escape(&config.node_name))
        .replace("{VERSION}", env!("CARGO_PKG_VERSION"))
        .replace("{NAVIGATION}", "")
        .replace("{GEN_TIME}", "0ms")
        .replace("{PAGE_CONTENT}", content)
}

pub(super) fn default_base_template() -> &'static str {
    "#!c=0\n>{NODE_NAME}\n\n{PAGE_CONTENT}\n<\n-\n`a`F666`[Served by rngit`:/page/index.mu] - Generated by rngit`f\n"
}
